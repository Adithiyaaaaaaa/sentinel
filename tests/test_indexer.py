def write(root: Path, relative: str, content: str) -> None:
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")


def test_indexes_measured_languages_lines_and_hashes(tmp_path: Path) -> None:
    write(tmp_path, "api/main.py", "def hello():\n    return 'hi'\n")
    write(tmp_path, "web/page.tsx", "export const title = 'Hello';\n")
    write(tmp_path, "empty.rs", "")
    result = index_repository(tmp_path)
    assert result.total_files == 3
    assert result.total_lines == 3
    assert result.languages == {
        "Python": {"files": 1, "lines": 2},
        "TypeScript": {"files": 1, "lines": 1},
        "Rust": {"files": 1, "lines": 0},
    }
    source = (tmp_path / "api/main.py").read_bytes()
    indexed = next(file for file in result.files if file.path == "api/main.py")
    assert indexed.sha256 == hashlib.sha256(source).hexdigest()
    assert indexed.size_bytes == len(source)
    assert result.total_bytes == sum(file.size_bytes for file in result.files)
    assert result.branch == "test-branch"


def test_ignores_builds_binary_generated_and_private_environment(tmp_path: Path) -> None:
    for path in (".git/objects/object.py", "node_modules/dep/a.js", "dist/app.js", ".venv/site.py", "generated.min.js", "types.generated.cs"):
        write(tmp_path, path, "some content\n")
    write(tmp_path, "generated.py", "# This file is automatically generated.\nx = 1\n")
    write(tmp_path, ".env", "SECRET=should-not-be-read\n")
    write(tmp_path, "keep.py", "value = 1\n")
    (tmp_path / "binary.py").write_bytes(b"abc\x00def")
    (tmp_path / "non_utf8.py").write_bytes(b"\xff\xfeinvalid")
    result = index_repository(tmp_path)
    assert [file.path for file in result.files] == ["keep.py"]
    assert result.skipped_files >= 5


def test_nested_ignore_and_user_patterns(tmp_path: Path) -> None:
    write(tmp_path, ".gitignore", "*.log\nignored.py\nsub/*.py\n!sub/keep.py\n")
    write(tmp_path, "sub/.gitignore", "!other.py\n")
    write(tmp_path, ".sentinelignore", "private/\n")
    for path in ("ignored.py", "sub/keep.py", "sub/other.py", "sub/no.py", "private/key.py", "custom.ts", "app.py"):
        write(tmp_path, path, "value = 1\n")
    result = index_repository(tmp_path, ignore_patterns=["custom.ts"])
    paths = {file.path for file in result.files}
    assert {"app.py", "sub/keep.py", "sub/other.py"} <= paths
    assert not {"ignored.py", "sub/no.py", "private/key.py", "custom.ts"} & paths


def test_detects_manifests_and_configuration_without_execution(tmp_path: Path) -> None:
    write(tmp_path, "package.json", json.dumps({"packageManager": "pnpm@10.0.0", "dependencies": {"react": "^19", "next": "^15"}, "devDependencies": {"vitest": "^3"}, "scripts": {"postinstall": "never execute me"}}))
    write(tmp_path, "pyproject.toml", '[project]\nname = "fixture"\ndependencies = ["fastapi>=0.115", "pytest>=8"]\n')
    write(tmp_path, "Dockerfile", "FROM scratch\n")
    write(tmp_path, ".github/workflows/ci.yml", "name: Tests\n")
    result = index_repository(tmp_path)
    assert result.frameworks == ["FastAPI", "Next.js", "React"]
    assert result.package_managers == ["npm", "pip", "pnpm"]
    assert result.test_frameworks == ["Vitest", "pytest"]
    assert result.has_ci is True
    assert result.has_docker is True
    assert len(result.dependencies) == 5


