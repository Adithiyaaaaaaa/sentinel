def test_git_metadata_ignores_inherited_repository_overrides(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    from types import SimpleNamespace

    monkeypatch.setenv("GIT_DIR", "unrelated/.git")
    monkeypatch.setenv("GIT_WORK_TREE", "unrelated")
    monkeypatch.setenv("GIT_CONFIG_COUNT", "1")
    environments = []

    def git_run(_arguments, **kwargs):
        environments.append(kwargs["env"])
        return SimpleNamespace(returncode=0, stdout="main\n")

    monkeypatch.setattr(indexer.subprocess, "run", git_run)
    _git_metadata(tmp_path)
    assert len(environments) == 2
    for environment in environments:
        assert "GIT_DIR" not in environment
        assert "GIT_WORK_TREE" not in environment
        assert "GIT_CONFIG_COUNT" not in environment
        assert environment["GIT_CONFIG_GLOBAL"] == indexer.os.devnull


