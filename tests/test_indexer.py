def test_file_size_cap_and_progress(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(indexer, "MAX_FILE_BYTES", 32)
    write(tmp_path, "large.py", "x" * 33)
    write(tmp_path, "small.py", "value = 1\n")
    events: list[tuple[int, str]] = []
    result = index_repository(tmp_path, progress=lambda value, message: events.append((value, message)))
    assert [file.path for file in result.files] == ["small.py"]
    assert "oversized" in result.warnings[0]
    assert [value for value, _ in events] == sorted(value for value, _ in events)
    assert events[-1][0] == 95


def test_never_follows_symlinks(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    write(outside, "secret.py", "SECRET = 'never-index'\n")
    root = tmp_path / "repository"
    root.mkdir()
    try:
        (root / "escape.py").symlink_to(outside / "secret.py")
        (root / "linked-folder").symlink_to(outside, target_is_directory=True)
    except OSError:
        pytest.skip("Host does not grant symbolic-link creation")
    result = index_repository(root)
    assert result.total_files == 0
    with pytest.raises(ValueError, match="symbolic link"):
        index_repository(root / "linked-folder")


